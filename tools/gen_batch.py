"""Regenerate the b01-b21 fight scripts reproducibly.

The batch used to be generated by running gen_fight 21 times by hand, so the
exact arguments lived only in shell history — a later regeneration could not be
reproduced. This file IS that record.

`caster` picks which side lands the finishing ultimate, and therefore which side
WINS. It defaults to "left" inside gen_fight; leaving every fight on the default
made all 21 end with the left fighter winning on exactly 40 HP, which makes the
"who wins?" hook predictable and the batch look mass-produced. The table below
deliberately mixes both sides.

The ult id and its vfx are derived from characters.json (the ultimate is the
skill with type=="ultimate"), so they cannot drift out of sync with the data.
gen_fight only uses vfx to decide whether the caster closes distance first; the
on-screen effect comes from the character data at render time.

Usage:
  python3 tools/gen_batch.py              # regenerate every fight
  python3 tools/gen_batch.py b03 b14      # only these (prefix match)
  python3 tools/gen_batch.py --list       # show the table, write nothing
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "pixel_battle/data/scripts"
ULT_MS = 45000

# (stem, left, right, arena, caster)  — caster is the winner.
BATCH = [
    ("b01_lumen_jugg",        "lux",         "mordekaiser", "frost", "left"),
    ("b02_wildfire_vanguard", "jinx",        "garen",       "dusk",  "left"),
    ("b03_frostbow_cleaver",  "ashe",        "cleaver",     "frost", "right"),
    ("b04_deadeye_bulwark",   "deadeye",     "bulwark",     "frost", "left"),
    ("b05_quarrel_ironfist",  "quarrel",     "ironfist",    "dojo",  "right"),
    ("b06_pyre_wrecker",      "pyre",        "wrecker",     "magma", "left"),
    ("b07_venom_reaver",      "venom",       "reaver",      "dusk",  "left"),
    ("b08_outlaw_skylance",   "outlaw",      "pantheon",    "dojo",  "right"),
    ("b09_jugg_outlaw",       "mordekaiser", "outlaw",      "magma", "right"),
    ("b10_vanguard_wildfire", "garen",       "jinx",        "magma", "left"),
    ("b11_ronin_cleaver",     "yasuo",       "cleaver",     "dojo",  "left"),
    ("b12_shade_deadeye",     "katarina",    "deadeye",     "frost", "right"),
    ("b13_skylance_lumen",    "pantheon",    "lux",         "frost", "left"),
    ("b14_bulwark_shade",     "bulwark",     "katarina",    "dojo",  "right"),
    ("b15_cyclone_ironfist",  "cyclone",     "ironfist",    "ruins", "left"),
    ("b16_wrecker_venom",     "wrecker",     "venom",       "magma", "right"),
    ("b17_warlock_vanguard",  "warlock",     "garen",       "ruins", "left"),
    ("b18_cleaver_warlock",   "cleaver",     "warlock",     "dojo",  "right"),
    ("b19_necro_ironfist",    "necro",       "ironfist",    "ruins", "right"),
    ("b20_totem_wrecker",     "totem",       "wrecker",     "dusk",  "left"),
    ("b21_forge_reaver",      "forge",       "reaver",      "magma", "right"),
]


def _ultimate(cid: str) -> tuple[str, str]:
    data = json.loads((ROOT / "pixel_battle/data/characters.json")
                      .read_text(encoding="utf-8"))
    chars = data.get("characters", data)
    entry = chars[cid] if isinstance(chars, dict) else \
        next(c for c in chars if c.get("id") == cid)
    skills = entry["skills"]
    u = next((s for s in skills if s.get("type") == "ultimate"), skills[-1])
    return u["id"], u.get("vfx", "slam")


def generate(stem: str, left: str, right: str, arena: str, caster: str) -> None:
    ult_id, vfx = _ultimate(left if caster == "left" else right)
    out = SCRIPTS / f"{stem}.yaml"
    cmd = [sys.executable, "-m", "pixel_battle.scripts.gen_fight",
           left, right, ult_id, vfx, "_", str(out), str(ULT_MS)]
    if caster == "right":
        cmd.append("--caster-right")
    r = subprocess.run(cmd, cwd=str(ROOT), capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"{stem}: gen_fight failed\n{r.stderr or r.stdout}")
    print((r.stdout or "").rstrip())
    # gen_fight does not know about arenas; re-attach it so the render picks the
    # right stage. Without this every regenerated fight silently falls back.
    text = out.read_text(encoding="utf-8").rstrip("\n")
    out.write_text(f"{text}\narena: {arena}\n", encoding="utf-8")


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--list" in sys.argv:
        for row in BATCH:
            print(f"{row[0]:26} {row[1]:12} vs {row[2]:12} arena={row[3]:6} winner={row[4]}")
        n_right = sum(1 for r in BATCH if r[4] == "right")
        print(f"\n{len(BATCH)} fights: left wins {len(BATCH)-n_right}, right wins {n_right}")
        return 0
    todo = [r for r in BATCH if not args or any(r[0].startswith(a) for a in args)]
    if not todo:
        print(f"no fight matched {args}")
        return 1
    for row in todo:
        generate(*row)
    print(f"\nregenerated {len(todo)} fight script(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
